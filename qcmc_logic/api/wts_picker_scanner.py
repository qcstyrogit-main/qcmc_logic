"""WTS-specific scanner Picker verification; never uses Manufacturing Stock Entry APIs.

Scanner can verify existing WTS Storage Allocation child rows, then atomically
receive the transfer through its existing ERPNext after-submit hooks.
"""
from collections import defaultdict
from decimal import Decimal, InvalidOperation
import secrets

import frappe
from frappe.utils import get_datetime, now_datetime

from qcmc_logic.api.warehouse_workflow import (
    WorkflowError, authenticated_user, active_employee, error_response,
    parse_json, request_uuid,
)
from qcmc_logic.api.warehouse_transfer_scanner import _clean_wts, _wts_fingerprint
from qcmc_logic.utils import ensure_scanner_warehouse_access
from qcmc_logic.warehouse_capacity import lock_warehouses
from qcmc_logic.warehouse_transfer_allocation import linked_allocations, stock_quantity, uses_allocation
from qcmc_logic.api.warehouse_allocation import _validate_location, _live_location_capacity
from qcmc_logic import wrr_allocation as wrr

EPSILON = Decimal("0.000001")


def _number(value):
    try:
        result = Decimal(str(value))
    except (TypeError, ValueError, InvalidOperation):
        raise WorkflowError("INVALID_QUANTITY", "Quantity must be a valid number.")
    if not result.is_finite() or result <= 0:
        raise WorkflowError("INVALID_QUANTITY", "Quantity must be greater than zero.")
    return result


def _load_handover(handover_qr, user, mutation=False, allow_completed=False):
    payload = parse_json(handover_qr, {})
    if not isinstance(payload, dict) or payload.get("type") != "QCMC_WTS_HANDOVER" or payload.get("version") != 1:
        raise WorkflowError("INVALID_HANDOVER_QR", "Scan the WTS Handover QR generated by Checker.")
    name = _clean_wts(payload.get("warehouse_transfer"))
    if mutation:
        # Take common capacity lock before the WTS document lock, matching
        # other allocation writers and avoiding duplicate receipts.
        warehouse = frappe.db.get_value("Warehouse Transfer", name, "target_warehouse")
        if not warehouse:
            raise WorkflowError("WTS_NOT_FOUND", "Warehouse Transfer not found.")
        lock_warehouses([warehouse])
        frappe.db.sql("select name from `tabWarehouse Transfer` where name=%s for update", name)
    if not frappe.db.exists("Scanner WTS Handover", name):
        raise WorkflowError("HANDOVER_NOT_FOUND", "WTS Checker handover does not exist.")
    handover = frappe.get_doc("Scanner WTS Handover", name)
    stored = handover.get_password("handover_token", raise_exception=False) or ""
    if not stored or not secrets.compare_digest(stored, str(payload.get("token") or "")):
        raise WorkflowError("INVALID_HANDOVER_QR", "Invalid WTS Handover token.", status=403)
    if not handover.expires_at or (get_datetime(handover.expires_at) < now_datetime() and not (allow_completed and handover.status == "COMPLETED")):
        raise WorkflowError("HANDOVER_EXPIRED", "WTS Handover QR expired. Generate a new QR.", status=403)
    if handover.status not in (("CHECKED", "ALLOCATION_CREATED", "COMPLETED") if allow_completed else ("CHECKED", "ALLOCATION_CREATED")):
        raise WorkflowError("HANDOVER_NOT_OPEN", "WTS Handover is already completed or cancelled.")
    transfer = frappe.get_doc("Warehouse Transfer", name)
    if transfer.docstatus != 1 or (transfer.transfer_status != "Transferred" and not (allow_completed and handover.status == "COMPLETED" and transfer.transfer_status == "Received")):
        raise WorkflowError("WTS_NOT_OPEN", "WTS must be submitted and Transferred, not Received.")
    if not uses_allocation(transfer) or not transfer.get("custom_apply_putaway_rule"):
        raise WorkflowError("ALLOCATION_NOT_ENABLED", "Enable WTS Storage Allocation and Apply Putaway Rule before scanning.")
    if handover.status != "COMPLETED" and _wts_fingerprint(transfer) != handover.source_fingerprint:
        raise WorkflowError("SOURCE_DOCUMENT_CHANGED", "WTS changed after Checker verification. Review it in ERPNext.")
    # A single person can be Checker and Picker. No Warehouse Picker role
    # or distinct user is required; warehouse authorization remains in force.
    permitted = False
    warehouses = (transfer.target_warehouse,) if mutation else (transfer.source_warehouse, transfer.target_warehouse)
    for warehouse in warehouses:
        if not warehouse:
            continue
        try:
            ensure_scanner_warehouse_access(user, [warehouse], require_transact=mutation)
            permitted = True
            break
        except frappe.PermissionError:
            continue
    if not permitted:
        raise WorkflowError("WAREHOUSE_PERMISSION_DENIED", "Scanner operator cannot access the WTS warehouse.", status=403)
    return handover, transfer


def _row_response(allocation, row):
    return {
        "allocation_id": row.allocation_id,
        "source_row": row.source_row,
        "item_code": row.item_code,
        "stock_uom": row.stock_uom,
        "quantity": float(row.suggested_qty or 0),
        "suggested_location": row.suggested_location or "",
        "actual_location": row.actual_location or "",
        "actual_qty": float(row.actual_qty or 0),
        "status": row.status,
    }


def _allocation_result(transfer):
    allocations = linked_allocations(transfer.name)
    return {
        "success": True, "warehouse_transfer": transfer.name,
        "existing_allocations": [{
            "name": a.name, "status": a.status, "warehouse": a.warehouse,
            "rows": [_row_response(a, r) for r in a.locations],
        } for a in allocations],
        "allocation_ready": bool([a for a in allocations if a.status != "Cancelled"]) and all(
            a.locations and all(
                r.status == "VERIFIED" and r.actual_location
                and abs(Decimal(str(r.actual_qty or 0)) - Decimal(str(r.suggested_qty or 0))) <= EPSILON
                for r in a.locations
            ) for a in allocations if a.status != "Cancelled"
        ),
    }


def validate_scanner_allocations(doc):
    """Used by the WTS save hook before stock can be received.

    Ensure all authoritative stock rows and physically verified allocation
    quantities agree; no allocations may disappear or be regenerated.
    """
    if not uses_allocation(doc):
        raise WorkflowError("ALLOCATION_NOT_ENABLED", "WTS has no storage allocation.")
    expected = {}
    for item in doc.get("transfer_items") or []:
        if not item.item_code:
            continue
        quantity, stock_item = stock_quantity(item, item.received_qty)
        if not stock_item.is_stock_item or quantity <= 0:
            continue
        expected[(item.name, item.item_code, stock_item.stock_uom)] = Decimal(str(quantity))
    allocations = linked_allocations(doc.name)
    if not expected or not allocations:
        raise WorkflowError("ALLOCATION_INCOMPLETE", "No receiving Storage Allocations exist.")
    actual = defaultdict(lambda: Decimal("0"))
    for allocation in allocations:
        if allocation.status == "Cancelled" and not allocation.locations:
            continue
        if allocation.status == "Cancelled" or allocation.docstatus != 0 or allocation.warehouse != doc.target_warehouse:
            raise WorkflowError("ALLOCATION_INCOMPLETE", "An allocation is closed or belongs to another warehouse.")
        for row in allocation.locations:
            key = (row.source_row, row.item_code, row.stock_uom)
            if row.source_doctype != "Warehouse Transfer" or row.source_document != doc.name or key not in expected:
                raise WorkflowError("SOURCE_DOCUMENT_CHANGED", "Allocation has an unexpected source row.")
            if row.status != "VERIFIED" or not row.actual_location:
                raise WorkflowError("ALLOCATION_INCOMPLETE", "Scan and verify every storage location before completing.")
            qty = Decimal(str(row.actual_qty or 0))
            suggested = Decimal(str(row.suggested_qty or 0))
            if qty <= 0 or abs(qty - suggested) > EPSILON:
                raise WorkflowError("ALLOCATION_QUANTITY_MISMATCH", "Verified row quantity must match its required allocation quantity.")
            location = frappe.get_cached_doc("Storage Location", row.actual_location)
            if location.disabled or location.is_group or location.custom_warehouse != doc.target_warehouse:
                raise WorkflowError("LOCATION_WAREHOUSE_MISMATCH", "Verified Storage Location is invalid for this warehouse.")
            if location.custom_restricted_item and location.custom_restricted_item != row.item_code:
                raise WorkflowError("LOCATION_ITEM_MISMATCH", "Verified Storage Location is restricted to another item.")
            actual[key] += qty
    if set(actual) != set(expected) or any(abs(actual[k] - v) > EPSILON for k, v in expected.items()):
        raise WorkflowError("ALLOCATION_QUANTITY_MISMATCH", "Total verified quantities must match every receiving WTS stock row.")
    return allocations


@frappe.whitelist(allow_guest=True, methods=["POST"])
def get_picker_context(handover_qr, mobile_token=None):
    """Read current verified rows for this Handover (either scanner device)."""
    try:
        user = authenticated_user(mobile_token)
        active_employee(user)
        handover, transfer = _load_handover(handover_qr, user)
        result = _allocation_result(transfer)
        result.update({
            "has_discrepancy": bool(handover.has_discrepancy),
            "check_date": str(handover.check_date or ""),
            "batch_id": handover.name,
            "checker": frappe.db.get_value("Assign Checker", handover.checker, "checker_name"),
            "status": handover.status,
            "source_warehouse": transfer.source_warehouse,
            "target_warehouse": transfer.target_warehouse,
        })
        return result
    except WorkflowError as exc:
        return error_response(exc)
    except Exception:
        frappe.log_error(frappe.get_traceback(), "wts_picker_scanner.get_picker_context")
        return error_response(WorkflowError("ERP_VALIDATION_FAILED", "Unable to load WTS Storage Allocation."))


@frappe.whitelist(allow_guest=True, methods=["POST"])
def verify_location(handover_qr, warehouse_allocation, allocation_id, scanned_location_id,
                    actual_quantity, transaction_id, device_id=None, mobile_token=None):
    savepoint = "wts_picker_verify_location"
    started = False
    try:
        user = authenticated_user(mobile_token)
        active_employee(user)
        request_uuid(transaction_id, "transaction_id")
        frappe.db.savepoint(savepoint)
        started = True
        handover, transfer = _load_handover(handover_qr, user, mutation=True)
        # Checker quantities (including shortages, excess and extra rows)
        # were already written to WTS Received Qty before Putaway planning.
        name = str(warehouse_allocation or "").strip()
        frappe.db.sql("select name from `tabStorage Allocation` where name=%s for update", name)
        allocation = next((a for a in linked_allocations(transfer.name) if a.name == name), None)
        if not allocation or allocation.docstatus != 0 or allocation.status == "Cancelled":
            raise WorkflowError("ALLOCATION_NOT_FOUND", "No open linked WTS Storage Allocation found.")
        row = next((r for r in allocation.locations if r.allocation_id == str(allocation_id or "").strip()), None)
        if not row or row.source_document != transfer.name or row.source_doctype != "Warehouse Transfer":
            raise WorkflowError("ALLOCATION_NOT_FOUND", "Allocation row is not linked to the scanned WTS.")
        if row.status == "UNALLOCATED":
            raise WorkflowError("ALLOCATION_INCOMPLETE", "No Putaway capacity was assigned to this row.")
        quantity = _number(actual_quantity)
        required = _number(row.suggested_qty)
        if abs(quantity - required) > EPSILON:
            raise WorkflowError("ALLOCATION_QUANTITY_MISMATCH", "For WTS, physically checked quantity must match the allocated row. Resolve shortages in ERPNext.")
        location = _validate_location(allocation, row, scanned_location_id, quantity)
        # Check current, shared physical reservations and live Putaway capacity.
        free, rule_name = _live_location_capacity(allocation, row, location)
        if free is not None and quantity > free + EPSILON:
            raise WorkflowError("LOCATION_CAPACITY_EXCEEDED", f"Storage Location {location.name} no longer has enough free capacity.")
        if row.status == "VERIFIED":
            if row.actual_location == location.name and abs(Decimal(str(row.actual_qty or 0)) - quantity) <= EPSILON:
                return _allocation_result(transfer)
            # Allow a verified destination to be corrected through another
            # physical location scan, with the same live-capacity checks.
            # Do not modify required or source quantities.
        row.actual_location = location.name
        row.actual_qty = float(quantity)
        row.putaway_rule = rule_name
        row.status = "VERIFIED"
        row.scanner_id = str(device_id or "").strip()
        row.user = user
        row.user_full_name = frappe.db.get_value("User", user, "full_name") or user
        row.scan_time = now_datetime()
        allocation.status = "In Progress"
        wrr._write(allocation, "save")
        return _allocation_result(transfer)
    except WorkflowError as exc:
        if started:
            frappe.db.rollback(save_point=savepoint)
        return error_response(exc)
    except Exception:
        if started:
            frappe.db.rollback(save_point=savepoint)
        frappe.log_error(frappe.get_traceback(), "wts_picker_scanner.verify_location")
        return error_response(WorkflowError("ERP_VALIDATION_FAILED", "Unable to verify WTS Storage Location."))


@frappe.whitelist(allow_guest=True, methods=["POST"])
def complete_allocation(handover_qr, transaction_id, mobile_token=None):
    savepoint = "wts_picker_complete"
    started = False
    try:
        user = authenticated_user(mobile_token)
        picker = active_employee(user)
        request_uuid(transaction_id, "transaction_id")
        frappe.db.savepoint(savepoint)
        started = True
        handover, doc = _load_handover(handover_qr, user, mutation=True, allow_completed=True)
        if handover.status == "COMPLETED" and doc.transfer_status == "Received":
            return {
                "success": True, "warehouse_transfer": doc.name,
                "status": "Received", "already_received": True,
                "allocations": [a.name for a in linked_allocations(doc.name)],
                "checker": handover.checker, "picker": handover.picker,
            }
        # The WTS is still Transferred here: received_qty commonly remains
        # zero until this receiver action. Populate it in-memory *before*
        # validating allocations against the authoritative receiving rows.
        # Nothing is posted until doc.save() successfully completes.
        # Never replace verified Received Qty with Issued Qty. The Checker
        # already saved the actual received quantities and extra WTS rows.
        allocations = validate_scanner_allocations(doc)
        # Recheck each verified destination against live capacity immediately
        # before ERPNext posts stock (warehouse lock held through this request).
        for allocation in allocations:
            for row in allocation.locations:
                location = _validate_location(allocation, row, row.actual_location, _number(row.actual_qty))
                free, _rule = _live_location_capacity(allocation, row, location)
                if free is not None and _number(row.actual_qty) > free + EPSILON:
                    raise WorkflowError("LOCATION_CAPACITY_EXCEEDED", f"Storage Location {location.name} no longer has free capacity.")
        doc.transfer_status = "Received"
        # Only this explicit scanner-confirmed save bypasses the WTS hook that
        # would otherwise reset physically checked rows from Putaway suggestions.
        doc.flags.qcmc_wts_scanner_receipt = True
        doc.save(ignore_permissions=True)
        handover.status = "COMPLETED"
        handover.picker = picker.name if picker.name != "Administrator" else ""
        handover.completed_at = now_datetime()
        handover.save(ignore_permissions=True)
        return {
            "success": True, "warehouse_transfer": doc.name,
            "status": "Received",
            "allocations": [a.name for a in allocations],
            "checker": handover.checker,
            "picker": picker.name,
        }
    except WorkflowError as exc:
        if started:
            frappe.db.rollback(save_point=savepoint)
        return error_response(exc)
    except Exception:
        if started:
            frappe.db.rollback(save_point=savepoint)
        frappe.log_error(frappe.get_traceback(), "wts_picker_scanner.complete_allocation")
        return error_response(WorkflowError("ERP_VALIDATION_FAILED", "WTS receiving failed and the transaction was rolled back."))
