const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
const events=[];
const context={frappe:{ui:{form:{on:(dt,handlers)=>events.push([dt,handlers])}}}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('qcmc_logic/public/js/delivery_note.js','utf8'),context);
const configure=context.configure_delivery_note_return_allocation;
const changes=[];
const fields=[];
const grid={docfields:[{fieldname:'location',options:'Storage Location',hidden:0},{fieldname:'accounting_location',options:'Location',hidden:0}],update_docfield_property:(...args)=>fields.push(args)};
const frm={doc:{is_return:1,docstatus:0,custom_storage_allocation_enabled:1,custom_apply_putaway_rule:0},fields_dict:{items:{grid}},is_new:()=>false,set_df_property:(...args)=>changes.push(args),refresh_field:()=>{}};
configure(frm);
assert.equal(frm.doc.custom_apply_putaway_rule,0);
assert(fields.some(([field,prop,value])=>field==='location'&&prop==='hidden'&&value===1));
assert(!fields.some(([field])=>field==='accounting_location'));
frm.doc.is_return=0;
configure(frm);
assert(fields.some(([field,prop,value])=>field==='location'&&prop==='hidden'&&value===0));
assert(changes.some(([field,prop,value])=>field==='custom_apply_putaway_rule'&&prop==='hidden'&&value===1));
console.log('Delivery Note return-only checkbox, manual choice and storage column restore checks passed');
