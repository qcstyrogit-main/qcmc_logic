const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
let nativeCalls=0;
const context={qcmc_logic:{stock_entry:{}},frappe:{provide:()=>{},ui:{form:{on:()=>{}}}},erpnext:{apply_putaway_rule:()=>{nativeCalls++;}}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('qcmc_logic/public/js/stock_entry.js','utf8'),context);
const api=context.qcmc_logic.stock_entry;
const changes=[];
const grid={docfields:[{fieldname:'to_location',options:'Storage Location',hidden:0}],update_docfield_property:(...args)=>changes.push(args)};
const frm={doc:{doctype:'Stock Entry',stock_entry_type:'Material Receipt',apply_putaway_rule:0,custom_storage_allocation_enabled:1},fields_dict:{items:{grid}},is_new:()=>false,set_df_property:()=>{},refresh_field:()=>{}};
api.configure_storage_allocation(frm);
assert.equal(frm.doc.apply_putaway_rule,0);
context.erpnext.apply_putaway_rule(frm,'Material Receipt');
assert.equal(nativeCalls,0,'Material Receipt checkbox must preserve bulk rows');
frm.doc.stock_entry_type='Manufacture';
api.configure_storage_allocation(frm);
context.erpnext.apply_putaway_rule(frm,'Manufacture');
assert.equal(nativeCalls,1,'Other types retain native putaway handling');
assert(changes.some(([field,prop,value])=>field==='to_location'&&prop==='hidden'&&value===0));
console.log('Material Receipt keeps bulk rows and manual checkbox; other Stock Entry types retain native behavior');
